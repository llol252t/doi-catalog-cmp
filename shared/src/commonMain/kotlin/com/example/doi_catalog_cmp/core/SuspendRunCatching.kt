package com.example.doi_catalog_cmp.core

import kotlinx.coroutines.CancellationException

internal inline fun <T> suspendRunCatching(block: () -> T): Result<T> =
    try {
        Result.success(block())
    } catch (e: CancellationException) {
        throw e
    } catch (e: Exception) {
        Result.failure(e)
    }
